package com.jarvis.assistant.agentic.soul

import android.content.Context
import android.util.Log
import java.io.File

/**
 * Loads and parses SKILL.md skill files from:
 * 1. Bundled APK assets (`assets/skills/<skill-name>/SKILL.md`)
 * 2. User-customizable external directory (`filesDir/skills/<skill-name>/SKILL.md`)
 * 3. Room DB (`user_synthesized_skills`)
 *
 * Ensures JARVIS has live awareness of all built-in functions and user-defined skills.
 */
class ExternalSkillLoader private constructor(private val context: Context) {

    private val soulDao by lazy { SoulDatabase.getInstance(context).soulDao() }

    companion object {
        private const val TAG = "ExternalSkillLoader"

        @Volatile
        private var INSTANCE: ExternalSkillLoader? = null

        fun getInstance(context: Context): ExternalSkillLoader {
            return INSTANCE ?: synchronized(this) {
                INSTANCE ?: ExternalSkillLoader(context.applicationContext).also { INSTANCE = it }
            }
        }
    }

    /**
     * Parses a SKILL.md string with YAML frontmatter into a SynthesizedSkillEntity.
     */
    fun parseSkillMarkdown(folderName: String, rawMarkdown: String, isAutoGenerated: Boolean = false): SynthesizedSkillEntity {
        var name = folderName
        var description = "Custom skill loaded from SKILL.md"
        var triggerPattern = "When task relates to $folderName"

        val lines = rawMarkdown.lines()
        if (lines.firstOrNull()?.trim() == "---") {
            for (i in 1 until lines.size) {
                val line = lines[i].trim()
                if (line == "---") break
                if (line.startsWith("name:")) {
                    name = line.removePrefix("name:").trim().removeSurrounding("\"")
                } else if (line.startsWith("description:")) {
                    description = line.removePrefix("description:").trim().removeSurrounding("\"")
                } else if (line.startsWith("trigger:")) {
                    triggerPattern = line.removePrefix("trigger:").trim().removeSurrounding("\"")
                }
            }
        }

        val bodySummary = rawMarkdown
            .replace(Regex("(?s)^---.*?---"), "")
            .trim()
            .take(500)

        return SynthesizedSkillEntity(
            skillId = "skill_md_$folderName",
            name = name,
            description = description,
            triggerPattern = triggerPattern,
            actionChainJson = bodySummary,
            usageCount = 1,
            successRate = 1.0f,
            autoGenerated = isAutoGenerated,
            isActive = true
        )
    }

    /**
     * Loads all skills from assets, local storage, and Room database.
     */
    suspend fun getAllAvailableSkills(): List<SynthesizedSkillEntity> {
        val result = LinkedHashMap<String, SynthesizedSkillEntity>()

        // 1. Load from Room DB
        try {
            soulDao.getActiveSkills().forEach { skill ->
                result[skill.name.lowercase()] = skill
            }
        } catch (e: Exception) {
            Log.w(TAG, "Failed to read DB skills: ${e.message}")
        }

        // 2. Load from bundled assets/skills/
        try {
            val assetSkillDirs = context.assets.list("skills") ?: emptyArray()
            for (dir in assetSkillDirs) {
                try {
                    val md = context.assets.open("skills/$dir/SKILL.md").bufferedReader().use { it.readText() }
                    val parsed = parseSkillMarkdown(dir, md, isAutoGenerated = false)
                    result.putIfAbsent(parsed.name.lowercase(), parsed)
                } catch (_: Exception) {
                }
            }
        } catch (_: Exception) {
        }

        // 3. Load from user external skills directory (filesDir/skills/)
        try {
            val userSkillsRoot = File(context.filesDir, "skills")
            if (userSkillsRoot.exists() && userSkillsRoot.isDirectory) {
                userSkillsRoot.listFiles()?.forEach { dir ->
                    val skillFile = if (dir.isDirectory) File(dir, "SKILL.md") else if (dir.name.endsWith(".md")) dir else null
                    if (skillFile != null && skillFile.exists()) {
                        val parsed = parseSkillMarkdown(dir.nameWithoutExtension, skillFile.readText(), isAutoGenerated = false)
                        result[parsed.name.lowercase()] = parsed
                    }
                }
            }
        } catch (e: Exception) {
            Log.w(TAG, "Failed to scan user skills dir: ${e.message}")
        }

        return result.values.toList()
    }

    /**
     * Saves or updates a user-created SKILL.md skill both on disk and in Room DB.
     */
    suspend fun saveOrUpdateSkillMarkdown(skillName: String, description: String, trigger: String, instructions: String) {
        val safeFolder = skillName.lowercase().replace(Regex("[^a-z0-9_-]"), "-")
        val mdContent = """
            ---
            name: "$skillName"
            description: "$description"
            trigger: "$trigger"
            ---
            
            $instructions
        """.trimIndent()

        try {
            val dir = File(File(context.filesDir, "skills"), safeFolder)
            dir.mkdirs()
            File(dir, "SKILL.md").writeText(mdContent)
        } catch (e: Exception) {
            Log.w(TAG, "Failed writing SKILL.md to disk: ${e.message}")
        }

        val entity = parseSkillMarkdown(safeFolder, mdContent, isAutoGenerated = true)
        soulDao.insertSkill(entity)
    }
}
