package com.jarvis.assistant.agentic.soul

import androidx.room.Entity
import androidx.room.PrimaryKey
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale
import java.util.UUID

/**
 * A skill synthesized automatically by JARVIS based on recurring user habits and commands.
 * These skills evolve and refine themselves continuously over time.
 */
@Entity(tableName = "user_synthesized_skills")
data class SynthesizedSkillEntity(
    @PrimaryKey
    val skillId: String = UUID.randomUUID().toString(),
    val name: String, // e.g. "Evening Hindi Chill Session", "Speed Code Commit Workflow"
    val description: String,
    val triggerPattern: String, // Spoken cues, time-of-day, or context condition
    val actionChainJson: String, // JSON array of sequential actions/tools
    val usageCount: Int = 0,
    val successRate: Float = 1.0f,
    val autoGenerated: Boolean = true,
    val isActive: Boolean = true,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis()
) {
    val formattedDate: String
        get() {
            val sdf = SimpleDateFormat("MMM dd, yyyy", Locale.getDefault())
            return sdf.format(Date(updatedAt))
        }
}
